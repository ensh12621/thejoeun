package day2;

public class _9_조건문 {

	public static void main(String[] args) {
		int age = 15;

		if (age >= 20) {
			System.out.println("성인입니다");
		}

		if (age < 20) {
			System.out.println("청소년입니다");
		}

		if (age >= 20) {
			System.out.println("성인입니다");
		} else {
			System.out.println("청소년입니다");
		}

	}
}
